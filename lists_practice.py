# ============================================================
#  ХАРАКТЕРИСТИКИ ТИПА list В PYTHON
# ============================================================
#
#  ┌─────────────────────┬───────────────────────────────────┐
#  │ Свойство            │ Значение                          │
#  ├─────────────────────┼───────────────────────────────────┤
#  │ Тип                 │ list (изменяемый, упорядоченный)  │
#  │ Индексация          │ с 0, отрицательные индексы с конца│
#  │ Дубликаты           │ допускаются                       │
#  │ Гетерогенность      │ элементы могут быть любых типов   │
#  │ Изменяемость        │ mutable (можно менять элементы)   │
#  │ Хешируемость        │ unhashable (нельзя как ключ dict) │
#  │ Доступ по индексу   │ O(1)                              │
#  │ Поиск элемента      │ O(n)                              │
#  │ Вставка в конец     │ O(1) амортизировано               │
#  │ Удаление с конца    │ O(1)                              │
#  │ Вставка в начало    │ O(n)                              │
#  │ Удаление из начала  │ O(n)                              │
#  │ Память              │ динамический массив ссылок        │
#  │ Сравнение           │ лексикографическое, поэлементное  │
#  │ Умножение           │ lst * n — повторяет элементы      │
#  │ Сложение            │ lst1 + lst2 — новый список        │
#  └─────────────────────┴───────────────────────────────────┘
#
# ============================================================
#  МЕТОДЫ list (все 11)
# ============================================================
#
#  ┌───────────────────────┬──────────────────────────────────┬─────────────┐
#  │ Метод                 │ Описание                         │ Возвращает  │
#  ├───────────────────────┼──────────────────────────────────┼─────────────┤
#  │ lst.append(x)         │ добавляет x в конец              │ None        │
#  │ lst.extend(iterable)  │ добавляет все элементы iterable  │ None        │
#  │ lst.insert(i, x)      │ вставляет x на позицию i         │ None        │
#  │ lst.remove(x)         │ удаляет первое вхождение x       │ None        │
#  │ lst.pop(i=-1)         │ удаляет и возвращает элемент по i│ элемент     │
#  │ lst.clear()           │ очищает список                   │ None        │
#  │ lst.index(x[,s[,e]])  │ индекс первого вхождения x       │ int         │
#  │ lst.count(x)          │ количество вхождений x           │ int         │
#  │ lst.sort(key=None,    │ сортирует на месте               │ None        │
#  │          reverse=False)│                                  │             │
#  │ lst.reverse()         │ разворачивает порядок на месте   │ None        │
#  │ lst.copy()            │ поверхностная копия              │ list        │
#  └───────────────────────┴──────────────────────────────────┴─────────────┘
#
# ============================================================
#  ВСТРОЕННЫЕ ФУНКЦИИ ДЛЯ РАБОТЫ СО СПИСКАМИ
# ============================================================
#
#  len(lst)         — длина списка
#  min(lst)         — минимальный элемент
#  max(lst)         — максимальный элемент
#  sum(lst)         — сумма элементов
#  sorted(lst)      — возвращает новый отсортированный список
#  reversed(lst)    — возвращает обратный итератор
#  enumerate(lst)   — возвращает итератор пар (индекс, элемент)
#  zip(lst1, lst2)  — возвращает итератор кортежей из пар
#  filter(fn, lst)  — фильтрует элементы через функцию
#  map(fn, lst)     — применяет функцию к каждому элементу
#  any(lst)         — True если хотя бы один элемент True
#  all(lst)         — True если все элементы True
#  list(iterable)   — создаёт список из итерируемого
#  del lst[i]       — удаляет элемент по индексу
#  del lst[i:j]     — удаляет срез
#  x in lst         — проверяет наличие элемента
#  x not in lst     — проверяет отсутствие элемента
#
# ============================================================
#  СОЗДАНИЕ СПИСКОВ
# ============================================================
#
#  lst = [1, 2, 3]                 # литерал
#  lst = list((1, 2, 3))           # из кортежа
#  lst = list("hello")             # ['h','e','l','l','o']
#  lst = list(range(5))            # [0, 1, 2, 3, 4]
#  lst = list({1, 2, 3})           # из множества
#  lst = [x**2 for x in range(5)]  # list comprehension
#  lst = [0] * 5                   # [0, 0, 0, 0, 0]
#
# ============================================================
#  СРЕЗЫ И ОПЕРАЦИИ С НИМИ
# ============================================================
#
#  lst[i]        — элемент по индексу
#  lst[i:j]      — срез от i до j (не включая j)
#  lst[i:j:k]    — срез с шагом k
#  lst[:j]       — от начала до j
#  lst[i:]       — от i до конца
#  lst[-i:]      — последние i элементов
#  lst[::k]      — каждый k-й элемент
#  lst[::-1]     — разворот списка (копия!)
#
#  lst[i:j] = [...]  — замена среза с возможным изменением длины
#  lst[i:i] = [...]  — вставка без удаления
#  lst[i:j] = []     — удаление среза
#  del lst[i:j]      — то же самое через del
#
# ============================================================
#  ОГРАНИЧЕНИЯ И ОСОБЕННОСТИ
# ============================================================
#
#  # list не может быть ключом словаря (unhashable)
#  d = {[1,2]: "value"}  # TypeError
#
#  # list не может быть элементом множества (unhashable)
#  s = {[1,2,3]}         # TypeError
#
#  # ОСТОРОЖНО: умножение копирует ссылки, а не объекты
#  bad = [[]] * 3         # все 3 элемента — один и тот же список!
#  good = [[] for _ in range(3)]  # три разных пустых списка
#
#  # Методы append/extend/insert/remove/sort/reverse — на месте,
#  # возвращают None, их НЕЛЬЗЯ вкладывать в print напрямую:
#  print(lst.append(4))   # напечатает None
#  # Правильно:
#  lst.append(4)
#  print(lst)
#
# ============================================================
#  ТИПИЧНЫЕ ПАТТЕРНЫ И ФИШКИ
# ============================================================
#
#  # Обмен значений
#  a, b = b, a
#
#  # Распаковка
#  first, *middle, last = [1, 2, 3, 4, 5]
#  # first=1, middle=[2,3,4], last=5
#
#  # Стек (LIFO) — append + pop()
#  stack = []
#  stack.append(1); stack.pop()
#
#  # Удаление дубликатов с сохранением порядка (Python 3.7+)
#  unique = list(dict.fromkeys(lst))
#
#  # Плоский список из вложенного
#  flat = [x for sub in nested for x in sub]
#
#  # Транспонирование матрицы
#  transposed = list(zip(*matrix))
#
#  # List comprehension с фильтрацией
#  [transform(x) for x in data if condition(x)]
#
# ============================================================






