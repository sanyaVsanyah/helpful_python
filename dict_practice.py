#  max(d)           — максимальный ключ
#  any(d)           — True если есть хотя бы один True-ключ
#  all(d)           — True если все ключи True
#  dict(iterable)   — создаёт словарь
#  del d[key]       — удаляет пару по ключу
#  key in d         — проверяет наличие ключа
#  key not in d     — проверяет отсутствие ключа
