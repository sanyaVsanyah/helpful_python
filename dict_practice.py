#  │ Свойство            │ Значение                          │
#  ├─────────────────────┼───────────────────────────────────┤
#  │ Тип                 │ dict (изменяемый, отображение)    │
#  │ Упорядоченность     │ сохраняет порядок вставки (3.7+)  │
#  │ Ключи               │ уникальные, хешируемые, неизменяемые│
#  │ Значения            │ любые типы, могут повторяться     │
#  │ Изменяемость        │ mutable (можно менять пары)       │
#  │ Хешируемость        │ unhashable (нельзя как ключ)      │
#  │ Доступ по ключу     │ O(1) в среднем                    │
#  │ Поиск ключа         │ O(1) в среднем                    │
#  │ Вставка             │ O(1) в среднем                    │
#  │ Удаление            │ O(1) в среднем                    │
#  │ Память              │ хеш-таблица, больше чем list      │
#  │ Сравнение           │ == (порядок не важен в 3.7+)      │
#  └─────────────────────┴───────────────────────────────────┘
#
# ============================================================
#  МЕТОДЫ dict (все 11)
# ============================================================
#
#  ┌──────────────────────────────┬──────────────────────────────────┬──────────────┐
#  │ Метод                        │ Описание                         │ Возвращает   │
#  ├──────────────────────────────┼──────────────────────────────────┼──────────────┤
#  │ d.get(key, default=None)     │ значение по ключу или default    │ значение     │
#  │ d.keys()                     │ представление всех ключей        │ dict_keys    │
#  │ d.values()                   │ представление всех значений      │ dict_values  │
#  │ d.items()                    │ представление пар (ключ, значение)│ dict_items   │
#  │ d.pop(key, default)          │ удаляет и возвращает значение    │ значение     │
#  │ d.popitem()                  │ удаляет и возвращает последнюю   │ (key, value) │
#  │                              │ пару (LIFO в 3.7+)               │              │
#  │ d.setdefault(key, default)   │ возвращает значение, если нет —  │ значение     │
#  │                              │ создаёт с default                │              │
#  │ d.update(other_dict)         │ обновляет/добавляет пары из другого│ None        │
#  │ d.clear()                    │ очищает словарь                  │ None         │
#  │ d.copy()                     │ поверхностная копия              │ dict         │
#  │ d.fromkeys(iterable, value)  │ создаёт словарь из ключей        │ dict         │
#  │                              │ (класс-метод)                    │              │
#  └──────────────────────────────┴──────────────────────────────────┴──────────────┘
#
