# ============================================================
#  ХАРАКТЕРИСТИКИ ТИПА tuple В PYTHON
# ============================================================
#
#  ┌─────────────────────┬───────────────────────────────────┐
#  │ Свойство            │ Значение                          │
#  ├─────────────────────┼───────────────────────────────────┤
#  │ Тип                 │ tuple (неизменяемый, упорядоченный)│
#  │ Индексация          │ с 0, отрицательные индексы с конца│
#  │ Дубликаты           │ допускаются                       │
#  │ Гетерогенность      │ элементы могут быть любых типов   │
#  │ Изменяемость        │ immutable (нельзя менять элементы)│
#  │ Хешируемость        │ hashable (если все элементы хеш.) │
#  │ Доступ по индексу   │ O(1)                              │
#  │ Поиск элемента      │ O(n)                              │
#  │ Память              │ занимает меньше чем list          │
#  │ Сравнение           │ лексикографическое, поэлементное  │
#  │ Умножение           │ tpl * n — повторяет элементы      │
#  │ Сложение            │ tpl1 + tpl2 — новый кортеж        │
#  │ Использование       │ ключи словаря, элементы множества │
#  └─────────────────────┴───────────────────────────────────┘
#
# ============================================================
#  МЕТОДЫ tuple (всего 2)
# ============================================================
#
#  ┌───────────────────────┬──────────────────────────────────┬─────────────┐
#  │ Метод                 │ Описание                         │ Возвращает  │
#  ├───────────────────────┼──────────────────────────────────┼─────────────┤
#  │ tpl.count(x)          │ количество вхождений x           │ int         │
#  │ tpl.index(x[,s[,e]])  │ индекс первого вхождения x       │ int         │
#  └───────────────────────┴──────────────────────────────────┴─────────────┘
#
# ============================================================
#  ВСТРОЕННЫЕ ФУНКЦИИ ДЛЯ РАБОТЫ С КОРТЕЖАМИ
# ============================================================
#
#  len(tpl)         — длина кортежа
#  min(tpl)         — минимальный элемент
#  max(tpl)         — максимальный элемент
#  sum(tpl)         — сумма элементов
#  sorted(tpl)      — возвращает отсортированный список (не кортеж!)
#  reversed(tpl)    — возвращает обратный итератор
#  enumerate(tpl)   — возвращает итератор пар (индекс, элемент)
#  zip(tpl1, tpl2)  — возвращает итератор кортежей из пар
#  any(tpl)         — True если хотя бы один элемент True
#  all(tpl)         — True если все элементы True
#  tuple(iterable)  — создаёт кортеж из итерируемого
#  x in tpl         — проверяет наличие элемента
#  x not in tpl     — проверяет отсутствие элемента
#  del tpl           — удаляет кортеж целиком (не элементы!)
#
# ============================================================
#  СОЗДАНИЕ КОРТЕЖЕЙ
# ============================================================
#
#  tpl = (1, 2, 3)                 # литерал
#  tpl = 1, 2, 3                   # скобки не обязательны
#  tpl = (1,)                      # кортеж из одного элемента (запятая!)
#  tpl = ()                        # пустой кортеж
#  tpl = tuple([1, 2, 3])          # из списка
#  tpl = tuple("hello")            # ('h','e','l','l','o')
#  tpl = tuple(range(5))           # (0, 1, 2, 3, 4)
#  tpl = tuple({1, 2, 3})          # из множества
#
# ============================================================
#  ОСОБЕННОСТИ И ФИШКИ
# ============================================================
#
#  # Распаковка (unpacking)
#  a, b, c = (1, 2, 3)             # a=1, b=2, c=3
#  a, *rest = (1, 2, 3, 4)        # a=1, rest=[2,3,4]
#  *start, last = (1, 2, 3, 4)    # start=[1,2,3], last=4
#  first, *middle, last = (1,2,3,4,5)  # first=1, middle=[2,3,4], last=5
#
#  # Обмен значений (на самом деле через кортежи)
#  a, b = b, a                      # равносильно: (a, b) = (b, a)
#
#  # Множественное возвращение из функции
#  def min_max(lst):
#      return min(lst), max(lst)    # возвращает кортеж (без скобок)
#
#  # Именованный кортеж (namedtuple)
#  from collections import namedtuple
#  Point = namedtuple('Point', ['x', 'y'])
#  p = Point(x=10, y=20)
#  print(p.x, p.y)                 # доступ по имени
#
#  # Кортеж как ключ словаря
#  d = {(1, 2): "value"}            # работает, если все элементы хешируемы
#
#  # Внимание: изменяемые элементы внутри кортежа
#  tpl = (1, [2, 3], 4)
#  tpl[1].append(5)                # можно! сам список изменяемый
#  tpl[1] = [6, 7]                 # нельзя! TypeError
#
#  # Конкатенация и умножение
#  tpl = (1, 2) + (3, 4)           # (1, 2, 3, 4)
#  tpl = (1,) * 5                  # (1, 1, 1, 1, 1)
#
#  # Срезы работают, но возвращают новый кортеж
#  tpl = (0, 1, 2, 3, 4)
#  tpl[1:4]                         # (1, 2, 3)
#  tpl[::-1]                        # (4, 3, 2, 1, 0)
#
# ============================================================